function loadWFHResourceCounts()
{
	var dataString = "action=loadWFHResourceAllow";
		$.ajax({ 
			type: "POST",url: "ajaxWFH.php" ,data: dataString,cache: false,
			success: function(html)
			{	 
				var dobj=jQuery.parseJSON(html);
				if(dobj.status==1)
				{
					$("#WFHFIELD").html(dobj.data);
					
				}
				else{
					alert(dobj.msg);
					location.reload();
				}
			} 
		});
	
	
}	




</script>